//! Generates api::outs from src/outptrs.txt (itself generated from Microsoft's Win32 metadata by
//! tools/win32md): for each function with pointer-sized out-parameters ("dll name i,j..."), a
//! type `outs::<Name>` whose `Outs::MASK` has bit `i` set for each of them, and `outs::mask(name)`
//! for the dispatcher. Handlers named after such a function take their arguments through
//! `c.args::<outs::Name>()`, whose `a::<I>()` does not compile for an out-parameter and whose
//! `out::<I>()` does not compile for anything else (review 2026-11-16: `c.a(i)` and `Out::addr`
//! let a handler take a pointer-sized out-parameter as a plain u32).
use std::collections::BTreeMap;
use std::fmt::Write as _;

type Error = Box<dyn std::error::Error>;

/// One line's (name, mask), or why it is not one.
fn parse(line: &str) -> Result<(&str, u64), String> {
    let mut f = line.split(' ');
    let (Some(_dll), Some(name), Some(args), None) = (f.next(), f.next(), f.next(), f.next()) else {
        return Err(format!("not \"dll name i,j...\": {line}"));
    };
    if !name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_') {
        return Err(format!("{name}: not a name"));
    }
    let mut mask = 0u64;
    for a in args.split(',') {
        let i: u32 = a.parse().map_err(|e| format!("{a}: not an argument index: {e}"))?;
        mask |= 1u64.checked_shl(i).ok_or(format!("argument {i} past the mask"))?;
    }
    Ok((name, mask))
}

fn main() -> Result<(), Error> {
    println!("cargo::rerun-if-changed=src/outptrs.txt");
    let text = std::fs::read_to_string("src/outptrs.txt")?;
    // (by name: a function some DLLs share, as the forwarders do, has one signature)
    let mut by_name = BTreeMap::<&str, u64>::new();
    for (n, line) in (1u32..).zip(text.lines()) {
        let (name, mask) = parse(line).map_err(|e| format!("src/outptrs.txt:{n}: {e}"))?;
        *by_name.entry(name).or_default() |= mask;
    }
    let mut o = String::from("// Generated by build.rs from src/outptrs.txt: do not edit.\n");
    for (name, mask) in &by_name {
        writeln!(o, "#[allow(non_camel_case_types, dead_code)]\npub struct {name};\nimpl super::Outs for {name} {{\n    const MASK: u64 = {mask:#x};\n}}")?;
    }
    o += "/// The pointer-sized out-parameters of the function `name` (bit i: argument i), 0 when none.\npub fn mask(name: &str) -> u64 {\n    match name {\n";
    for (name, mask) in &by_name {
        writeln!(o, "        \"{name}\" => {mask:#x},")?;
    }
    o += "        _ => 0,\n    }\n}\n";
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").ok_or("OUT_DIR")?).join("outs.rs");
    std::fs::write(out, o)?;
    Ok(())
}
